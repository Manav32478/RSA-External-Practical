"""```markdown
## Task 5: Apply Adversarial Training
Fine-tuning the model for 2 epochs on a 50:50 mixture of clean and FGSM (ε = 0.20) perturbed images.
```
"""

adv_model = BaselineCNN().to(device)
adv_model.load_state_dict(model.state_dict()) # Initialise with trained baseline weights
adv_optimizer = optim.Adam(adv_model.parameters(), lr=0.001)

print("Fine-tuning model using Adversarial Training (2 epochs)...")
adv_model.train()
for epoch in range(2):
    running_loss = 0.0
    for images, labels in train_loader:
        images, labels = images.to(device), labels.to(device)

        # Generate FGSM adversarial images for half the batch
        images.requires_grad = True
        outputs = adv_model(images)
        loss = criterion(outputs, labels)
        adv_model.zero_grad()
        loss.backward()
        data_grad = images.grad.data
        perturbed_images = fgsm_attack(images, 0.20, data_grad).detach()

        # Create 50:50 Mix
        half_batch = images.size(0) // 2
        mixed_images = torch.cat([images[:half_batch], perturbed_images[half_batch:]], dim=0)

        adv_optimizer.zero_grad()
        mixed_outputs = adv_model(mixed_images)
        mixed_loss = criterion(mixed_outputs, labels)
        mixed_loss.backward()
        adv_optimizer.step()
        running_loss += mixed_loss.item() * images.size(0)

    print(f"Epoch {epoch+1}/2 - Loss: {running_loss/len(train_loader.dataset):.4f}")

# Re-evaluation of Clean, FGSM, and PGD accuracies at epsilon = 0.20 for Adv Trained Model
adv_model.eval()
clean_correct = 0
fgsm_correct = 0
pgd_correct = 0
total = 0

for images, labels in test_loader:
    images, labels = images.to(device), labels.to(device)

    # Clean
    with torch.no_grad():
        outputs = adv_model(images)
        _, pred = torch.max(outputs, 1)
        clean_correct += (pred == labels).sum().item()

    # FGSM
    images.requires_grad = True
    outputs = adv_model(images)
    loss = criterion(outputs, labels)
    adv_model.zero_grad()
    loss.backward()
    data_grad = images.grad.data
    perturbed_fgsm = fgsm_attack(images, 0.20, data_grad)
    with torch.no_grad():
        outputs_fgsm = adv_model(perturbed_fgsm)
        _, pred_fgsm = torch.max(outputs_fgsm, 1)
        fgsm_correct += (pred_fgsm == labels).sum().item()

    # PGD
    perturbed_pgd = pgd_attack(adv_model, images, labels, 0.20, 0.05, num_iter=10)
    with torch.no_grad():
        outputs_pgd = adv_model(perturbed_pgd)
        _, pred_pgd = torch.max(outputs_pgd, 1)
        pgd_correct += (pred_pgd == labels).sum().item()

    total += labels.size(0)

adv_clean_acc = 100 * clean_correct / total
adv_fgsm_acc = 100 * fgsm_correct / total
adv_pgd_acc = 100 * pgd_correct / total

