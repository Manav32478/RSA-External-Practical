import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader, TensorDataset
import numpy as np
import matplotlib.pyplot as plt
import pandas as pd

# Set manual seed for reproducibility
torch.manual_seed(42)
np.random.seed(42)
device = torch.device('cpu')
print(f"Using device: {device}")

"""```markdown
## Task 1: Load MNIST and Train a Baseline CNN
We will define a CNN with two convolutional layers and two fully connected layers, then train it using Adam for 2 epochs on the CPU.
```
"""

# Load MNIST Dataset
transform = transforms.Compose([transforms.ToTensor()])
train_dataset = datasets.MNIST(root='./data', train=True, download=True, transform=transform)
test_dataset = datasets.MNIST(root='./data', train=False, download=True, transform=transform)

train_loader = DataLoader(train_dataset, batch_size=64, shuffle=True)
test_loader = DataLoader(test_dataset, batch_size=64, shuffle=False)

# Define the CNN architecture
class BaselineCNN(nn.Module):
    def __init__(self):
        super(BaselineCNN, self).__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(1, 16, kernel_size=5, padding=2),
            nn.ReLU(),
            nn.MaxPool2d(2),
            nn.Conv2d(16, 32, kernel_size=5, padding=2),
            nn.ReLU(),
            nn.MaxPool2d(2)
        )
        self.fc = nn.Sequential(
            nn.Linear(32 * 7 * 7, 128),
            nn.ReLU(),
            nn.Linear(128, 10)
        )

    def forward(self, x):
        x = self.conv(x)
        x = x.view(x.size(0), -1)
        x = self.fc(x)
        return x

model = BaselineCNN().to(device)
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

# Train the baseline model
print("Training baseline CNN for 2 epochs...")
model.train()
for epoch in range(2):
    running_loss = 0.0
    for images, labels in train_loader:
        images, labels = images.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()
        running_loss += loss.item() * images.size(0)
    epoch_loss = running_loss / len(train_loader.dataset)
    print(f"Epoch {epoch+1}/2 - Loss: {epoch_loss:.4f}")

# Report Clean Test Accuracy
def evaluate_clean(model, loader):
    model.eval()
    correct = 0
    total = 0
    with torch.no_grad():
        for images, labels in loader:
            images, labels = images.to(device), labels.to(device)
            outputs = model(images)
            _, predicted = torch.max(outputs.data, 1)
            total += labels.size(0)
            correct += (predicted == labels).sum().item()
    return 100 * correct / total

clean_acc = evaluate_clean(model, test_loader)
print(f"\nClean Test Accuracy: {clean_acc:.2f}%")

"""```markdown
## Tasks 2 & 3: Implement FGSM and PGD Attacks
We will define helper functions for executing both FGSM and PGD attacks on the target model.
```
"""

def fgsm_attack(image, epsilon, data_grad):
    perturbed_image = image + epsilon * data_grad.sign()
    perturbed_image = torch.clamp(perturbed_image, 0, 1)
    return perturbed_image

def pgd_attack(model, images, labels, epsilon, alpha, num_iter=10):
    perturbed_images = images.clone().detach().to(device)
    # Random initialization within L_infinity ball around clean images
    perturbed_images = perturbed_images + torch.empty_like(perturbed_images).uniform_(-epsilon, epsilon)
    perturbed_images = torch.clamp(perturbed_images, 0, 1).detach()

    for _ in range(num_iter):
        perturbed_images.requires_grad = True
        outputs = model(perturbed_images)
        loss = criterion(outputs, labels)
        model.zero_grad()
        loss.backward()

        # Gradient step
        data_grad = perturbed_images.grad.data
        perturbed_images = perturbed_images + alpha * data_grad.sign()
        # Projection step (projection onto L_infinity ball of size epsilon around original images)
        eta = torch.clamp(perturbed_images - images, min=-epsilon, max=epsilon)
        perturbed_images = torch.clamp(images + eta, min=0, max=1).detach()

    return perturbed_images

# Evaluation loop over various epsilon values
epsilons = [0.05, 0.10, 0.20, 0.30]
fgsm_accuracies = []
pgd_accuracies = []

print("Evaluating Baseline Model on FGSM and PGD Attacks...")
for eps in epsilons:
    fgsm_correct = 0
    pgd_correct = 0
    total = 0

    for images, labels in test_loader:
        images, labels = images.to(device), labels.to(device)

        # --- FGSM Evaluation ---
        images.requires_grad = True
        outputs = model(images)
        loss = criterion(outputs, labels)
        model.zero_grad()
        loss.backward()
        data_grad = images.grad.data
        perturbed_fgsm = fgsm_attack(images, eps, data_grad)

        with torch.no_grad():
            outputs_fgsm = model(perturbed_fgsm)
            _, predicted_fgsm = torch.max(outputs_fgsm.data, 1)
            fgsm_correct += (predicted_fgsm == labels).sum().item()

        # --- PGD Evaluation ---
        alpha = eps / 4
        perturbed_pgd = pgd_attack(model, images, labels, eps, alpha, num_iter=10)
        with torch.no_grad():
            outputs_pgd = model(perturbed_pgd)
            _, predicted_pgd = torch.max(outputs_pgd.data, 1)
            pgd_correct += (predicted_pgd == labels).sum().item()

        total += labels.size(0)

    fgsm_acc = 100 * fgsm_correct / total
    pgd_acc = 100 * pgd_correct / total
    fgsm_accuracies.append(fgsm_acc)
    pgd_accuracies.append(pgd_acc)
    print(f"Epsilon: {eps:.2f} | FGSM Accuracy: {fgsm_acc:.2f}% | PGD Accuracy: {pgd_acc:.2f}%")

